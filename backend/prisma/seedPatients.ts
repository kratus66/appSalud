export async function seedPatients(institutionId: string) {
  console.log('\n🏥 Creando pacientes de prueba...');
  let created = 0;
  let skipped = 0;

  for (const p of patients) {
    const existing = await prisma.patient.findFirst({
      where: { documentNumber: p.documentNumber, institutionId },
    });

    if (existing) {
      skipped++;
      continue;
    }

    await prisma.patient.create({
      data: {
        ...p,
        birthDate: new Date(p.birthDate),
        institutionId,
      },
    });
    created++;
  }

  console.log(`✅ Pacientes: ${created} creados, ${skipped} ya existían`);
}
